use std::path::Path;

use anyhow::{Context, Result};
use serde::Serialize;

use crate::{
    app_workspace::AppWorkspace,
    sync_descriptor::{
        load_sync_descriptor_set, NormalizedSyncDescriptor, NormalizedSyncGovernance,
        NormalizedSyncObjectEchoLoop, NormalizedSyncObjectMap, NormalizedSyncObjectProvenance,
    },
    utils::{
        artifacts::{self, Artifact, OverwriteMode},
        console, files,
    },
};

pub const SYNC_WORKER_PLAN_REPORT: &str = "sync_worker_plan.json";
pub const SYNC_WORKER_ACTIVATION_GATES: [&str; 7] = [
    "provider_live_certification",
    "provider_request_execution",
    "checkpoint_persistence",
    "idempotent_projection_writes",
    "scheduler_readiness_and_freshness",
    "cdc_broker_client",
    "worker_deployment_wiring",
];

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct SyncWorkerPlan {
    pub version: u32,
    pub generated_at: String,
    pub enabled: bool,
    pub activation_gates: Vec<&'static str>,
    pub worker_count: usize,
    pub backend_config_path: String,
    pub workers: Vec<GeneratedSyncWorker>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
struct SyncWorkerConfig {
    version: u32,
    enabled: bool,
    activation_gates: Vec<&'static str>,
    worker_count: usize,
    workers: Vec<GeneratedSyncWorker>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct GeneratedSyncWorker {
    pub name: String,
    pub source_schema: String,
    pub target_schema: String,
    pub mode: String,
    pub schedule: String,
    pub freshness_slo: String,
    pub checkpoint: SyncWorkerCheckpoint,
    pub readiness: SyncWorkerReadiness,
    pub retry: SyncWorkerRetryPolicy,
    pub dead_letter: SyncWorkerDeadLetterPolicy,
    pub governance: NormalizedSyncGovernance,
    pub objects: Vec<GeneratedSyncObject>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct GeneratedSyncObject {
    pub source: String,
    pub target: String,
    pub key: String,
    pub watermark: String,
    pub provenance: NormalizedSyncObjectProvenance,
    pub echo_loop: NormalizedSyncObjectEchoLoop,
    pub upsert: SyncWorkerUpsertPolicy,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct SyncWorkerCheckpoint {
    pub store: &'static str,
    pub scope: String,
    pub watermark_mode: String,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct SyncWorkerReadiness {
    pub freshness_slo: String,
    pub max_consecutive_failures: u32,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct SyncWorkerRetryPolicy {
    pub enabled: bool,
    pub max_attempts: u32,
    pub initial_backoff_ms: u64,
    pub max_backoff_ms: u64,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct SyncWorkerDeadLetterPolicy {
    pub enabled: bool,
    pub store: &'static str,
    pub poison_record_policy: &'static str,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct SyncWorkerUpsertPolicy {
    pub strategy: &'static str,
    pub stable_source_key: String,
}

pub fn run(workspace: &AppWorkspace) -> Result<SyncWorkerPlan> {
    console::stage("sync workers");
    let descriptor_set = load_sync_descriptor_set(&files::get_sync_descriptors_dir(workspace))?;
    let backend_config_path = files::get_backend_sync_workers_config_file(workspace);
    let plan = build_sync_worker_plan(
        descriptor_set.descriptors,
        app_relative_path(workspace, &backend_config_path),
    );

    write_report(workspace, &plan)?;
    artifacts::emit(&Artifact::generated_text(
        backend_config_path,
        render_sync_worker_config(&plan)?,
        OverwriteMode::Always,
    ))?;
    console::done("sync workers");
    Ok(plan)
}

pub fn build_sync_worker_plan(
    descriptors: Vec<NormalizedSyncDescriptor>,
    backend_config_path: String,
) -> SyncWorkerPlan {
    let workers = descriptors
        .into_iter()
        .map(sync_worker_from)
        .collect::<Vec<_>>();
    SyncWorkerPlan {
        version: 1,
        generated_at: chrono::offset::Utc::now().to_rfc3339(),
        enabled: false,
        activation_gates: SYNC_WORKER_ACTIVATION_GATES.to_vec(),
        worker_count: workers.len(),
        backend_config_path,
        workers,
    }
}

pub fn render_sync_worker_config(plan: &SyncWorkerPlan) -> Result<String> {
    let config = SyncWorkerConfig {
        version: plan.version,
        enabled: plan.enabled,
        activation_gates: plan.activation_gates.clone(),
        worker_count: plan.worker_count,
        workers: plan.workers.clone(),
    };
    let yaml = serde_yaml::to_string(&config)?;
    Ok(format!(
        "# Generated by scripts/appfw generate from .appfw/model/sync/*.yaml.\n# Do not put sync object maps, watermarks, retention, deletion, or drift behavior in .appfw/manifest.yaml.\n# Runtime execution remains disabled until activation gates are satisfied.\n{yaml}"
    ))
}

fn sync_worker_from(descriptor: NormalizedSyncDescriptor) -> GeneratedSyncWorker {
    GeneratedSyncWorker {
        name: descriptor.name.clone(),
        source_schema: descriptor.source_schema,
        target_schema: descriptor.target_schema,
        mode: descriptor.mode.clone(),
        schedule: descriptor.schedule,
        freshness_slo: descriptor.freshness_slo.clone(),
        checkpoint: SyncWorkerCheckpoint {
            store: "appfw_sync_checkpoint",
            scope: descriptor.name.clone(),
            watermark_mode: checkpoint_mode_for(&descriptor.mode),
        },
        readiness: SyncWorkerReadiness {
            freshness_slo: descriptor.freshness_slo,
            max_consecutive_failures: 3,
        },
        retry: SyncWorkerRetryPolicy {
            enabled: true,
            max_attempts: 3,
            initial_backoff_ms: 1_000,
            max_backoff_ms: 30_000,
        },
        dead_letter: SyncWorkerDeadLetterPolicy {
            enabled: true,
            store: "appfw_sync_dead_letter",
            poison_record_policy: "record_and_continue",
        },
        governance: descriptor.governance,
        objects: descriptor
            .objects
            .into_iter()
            .map(sync_object_from)
            .collect(),
    }
}

fn checkpoint_mode_for(sync_mode: &str) -> String {
    match sync_mode {
        "cdc_event" => "cdc_offset".to_string(),
        _ => sync_mode.to_string(),
    }
}

fn sync_object_from(object: NormalizedSyncObjectMap) -> GeneratedSyncObject {
    GeneratedSyncObject {
        upsert: SyncWorkerUpsertPolicy {
            strategy: "idempotent_source_key",
            stable_source_key: object.key.clone(),
        },
        provenance: object.provenance,
        echo_loop: object.echo_loop,
        source: object.source,
        target: object.target,
        key: object.key,
        watermark: object.watermark,
    }
}

fn write_report(workspace: &AppWorkspace, plan: &SyncWorkerPlan) -> Result<()> {
    let report_path = workspace.target_file(SYNC_WORKER_PLAN_REPORT);
    artifacts::safe_write(&report_path, serde_json::to_string_pretty(plan)? + "\n")
        .with_context(|| format!("could not write {}", report_path.display()))?;
    console::write(&report_path);
    Ok(())
}

fn app_relative_path(workspace: &AppWorkspace, path: &Path) -> String {
    path.strip_prefix(&workspace.app_root)
        .unwrap_or(path)
        .display()
        .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn descriptor() -> NormalizedSyncDescriptor {
        NormalizedSyncDescriptor {
            file: ".appfw/model/sync/salesforce_to_pipeline.yaml".to_string(),
            name: "salesforce_to_pipeline".to_string(),
            source_schema: "salesforce_crm_v1".to_string(),
            target_schema: "pipeline".to_string(),
            mode: "incremental_watermark".to_string(),
            schedule: "*/5 * * * *".to_string(),
            freshness_slo: "PT10M".to_string(),
            objects: vec![NormalizedSyncObjectMap {
                source: "Account".to_string(),
                target: "Account".to_string(),
                key: "Id".to_string(),
                watermark: "SystemModstamp".to_string(),
                provenance: NormalizedSyncObjectProvenance {
                    projection_of: "salesforce_crm_v1.Account".to_string(),
                    source_key_field: "Id".to_string(),
                    source_watermark_field: "SystemModstamp".to_string(),
                    source_origin_field: Some("AppFrameworkOrigin__c".to_string()),
                },
                echo_loop: NormalizedSyncObjectEchoLoop {
                    policy: "reject_self_origin".to_string(),
                    local_origin: "appfw:pipeline:salesforce_to_pipeline".to_string(),
                    source_origin_field: "AppFrameworkOrigin__c".to_string(),
                },
            }],
            governance: NormalizedSyncGovernance {
                classification: "confidential".to_string(),
                retention: Some("P2Y".to_string()),
                deletion: "tombstone".to_string(),
                source_drift: "fail_closed".to_string(),
            },
        }
    }

    fn cdc_descriptor() -> NormalizedSyncDescriptor {
        NormalizedSyncDescriptor {
            file: ".appfw/model/sync/salesforce_cdc_to_pipeline.yaml".to_string(),
            name: "salesforce_cdc_to_pipeline".to_string(),
            source_schema: "salesforce_crm_v1".to_string(),
            target_schema: "pipeline".to_string(),
            mode: "cdc_event".to_string(),
            schedule: "continuous".to_string(),
            freshness_slo: "PT2M".to_string(),
            objects: vec![NormalizedSyncObjectMap {
                source: "AccountChangeEvent".to_string(),
                target: "Account".to_string(),
                key: "ChangeEventHeader.recordIds[0]".to_string(),
                watermark: "ChangeEventHeader.replayId".to_string(),
                provenance: NormalizedSyncObjectProvenance {
                    projection_of: "salesforce_crm_v1.AccountChangeEvent".to_string(),
                    source_key_field: "ChangeEventHeader.recordIds[0]".to_string(),
                    source_watermark_field: "ChangeEventHeader.replayId".to_string(),
                    source_origin_field: Some("ChangeEventHeader.changeOrigin".to_string()),
                },
                echo_loop: NormalizedSyncObjectEchoLoop {
                    policy: "reject_self_origin".to_string(),
                    local_origin: "appfw:pipeline:salesforce_cdc_to_pipeline".to_string(),
                    source_origin_field: "ChangeEventHeader.changeOrigin".to_string(),
                },
            }],
            governance: NormalizedSyncGovernance {
                classification: "confidential".to_string(),
                retention: Some("P2Y".to_string()),
                deletion: "tombstone".to_string(),
                source_drift: "fail_closed".to_string(),
            },
        }
    }

    #[test]
    fn empty_plan_renders_disabled_worker_config() {
        let plan =
            build_sync_worker_plan(vec![], "backend/config/generated/sync_workers.yaml".into());

        assert!(!plan.enabled);
        assert_eq!(plan.activation_gates, SYNC_WORKER_ACTIVATION_GATES.to_vec());
        assert_eq!(plan.worker_count, 0);

        let rendered = render_sync_worker_config(&plan).expect("render worker config");
        assert!(rendered.contains("enabled: false"));
        assert!(rendered.contains("provider_live_certification"));
        assert!(rendered.contains("workers: []"));
    }

    #[test]
    fn descriptor_plan_adds_checkpoint_retry_dead_letter_and_upsert_policy_but_stays_disabled() {
        let plan = build_sync_worker_plan(
            vec![descriptor()],
            "backend/config/generated/sync_workers.yaml".into(),
        );

        assert!(!plan.enabled);
        assert!(plan
            .activation_gates
            .contains(&"idempotent_projection_writes"));
        assert_eq!(plan.worker_count, 1);
        let worker = &plan.workers[0];
        assert_eq!(worker.name, "salesforce_to_pipeline");
        assert_eq!(worker.checkpoint.store, "appfw_sync_checkpoint");
        assert_eq!(worker.checkpoint.scope, "salesforce_to_pipeline");
        assert_eq!(worker.readiness.freshness_slo, "PT10M");
        assert!(worker.retry.enabled);
        assert!(worker.dead_letter.enabled);
        assert_eq!(worker.objects[0].upsert.strategy, "idempotent_source_key");
        assert_eq!(worker.objects[0].upsert.stable_source_key, "Id");
        assert_eq!(
            worker.objects[0].provenance.projection_of,
            "salesforce_crm_v1.Account"
        );
        assert_eq!(worker.objects[0].echo_loop.policy, "reject_self_origin");

        let rendered = render_sync_worker_config(&plan).expect("render worker config");
        assert!(rendered.contains("enabled: false"));
        assert!(rendered.contains("worker_count: 1"));
        assert!(rendered.contains("source_schema: salesforce_crm_v1"));
        assert!(rendered.contains("store: appfw_sync_checkpoint"));
        assert!(rendered.contains("strategy: idempotent_source_key"));
        assert!(rendered.contains("projection_of: salesforce_crm_v1.Account"));
        assert!(rendered.contains("local_origin: appfw:pipeline:salesforce_to_pipeline"));
    }

    #[test]
    fn cdc_descriptor_plan_uses_offset_checkpoint_but_stays_disabled() {
        let plan = build_sync_worker_plan(
            vec![cdc_descriptor()],
            "backend/config/generated/sync_workers.yaml".into(),
        );

        assert!(!plan.enabled);
        assert!(plan.activation_gates.contains(&"cdc_broker_client"));
        let worker = &plan.workers[0];
        assert_eq!(worker.mode, "cdc_event");
        assert_eq!(worker.checkpoint.watermark_mode, "cdc_offset");
        assert_eq!(worker.schedule, "continuous");
        assert_eq!(worker.objects[0].watermark, "ChangeEventHeader.replayId");

        let rendered = render_sync_worker_config(&plan).expect("render worker config");
        assert!(rendered.contains("enabled: false"));
        assert!(rendered.contains("mode: cdc_event"));
        assert!(rendered.contains("watermark_mode: cdc_offset"));
        assert!(rendered.contains("cdc_broker_client"));
    }
}
